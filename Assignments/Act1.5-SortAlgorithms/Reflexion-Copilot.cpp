//Reflexion sobre el uso de Copilot

//1. ¿Que algoritmos fueron mas faciles de implementar gracias a Copilot?
//Los algoritmos que fueron mas faciles de implementar fueron los que ya habia
//trabajado anteriormente en clase, como Swap Sort, Bubble Sort, Selection Sort
//e Insertion Sort. Copilot fue util principalmente para complementar el codigo
//que ya tenia, por ejemplo, al agregar los contadores de comparaciones e
//intercambios sin tener que modificar completamente las funciones.

//2. ¿En que casos Copilot dio soluciones correctas inmediatamente y en cuales
//fue necesario corregirlas?
//En algunas partes sencillas, como agregar variables, generar listas aleatorias
//o medir el tiempo de ejecucion, las sugerencias fueron bastante directas.
//Sin embargo, hubo partes que fue necesario revisar, especialmente Merge Sort,
//porque pequeños errores en las condiciones de los ciclos podian hacer que no
//se terminaran de copiar los elementos de las listas. Tambien fue necesario
//revisar que Quick Sort realmente se estuviera llamando desde el programa.

//3. ¿Copilot ahorro tiempo o hizo que tuvieras que pensar mas?
//En general si ahorro tiempo, principalmente al momento de agregar nuevas
//funciones al codigo que ya tenia. Aun asi, no fue solamente copiar las
//sugerencias, porque tuve que revisar como se integraban con lo que habia
//realizado anteriormente y comprobar que cada algoritmo siguiera funcionando
//correctamente.

//4. Menciona un ejemplo concreto donde Copilot no resolvio directamente el
//problema y tuviste que razonar.
//Un ejemplo fue el funcionamiento de Merge Sort. Al probar el algoritmo fue
//necesario revisar las condiciones de los ciclos que agregaban los elementos
//restantes de las listas izquierda y derecha. Tuve que identificar que indice
//correspondia a cada lista y asegurarme de que tambien avanzara el indice de
//la lista original.

//5. ¿Que harias diferente si no tuvieras Copilot?
//Sin Copilot probablemente habria realizado la actividad por partes, utilizando
//el codigo visto en clase como base y probando cada modificacion antes de
//continuar con la siguiente. Tambien habria tenido que consultar mas
//documentacion para implementar aspectos como la medicion del tiempo en
//nanosegundos y la generacion del archivo CSV.